import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const desktopDir = resolve(scriptDir, '..');
const repoRoot = resolve(desktopDir, '..', '..');
const fixtureDir = resolve(repoRoot, 'packages', 'vault-api', 'tests', 'fixtures');
const outputPath = resolve(
  desktopDir,
  'src',
  'lib',
  'generated',
  'vault-api-contract-fixtures.ts',
);

const fixtures = {
  apiError: 'api_error.json',
  archivedEntryView: 'archived_entry_view.json',
  auditFinding: 'audit_finding.json',
  clientCapabilities: 'client_capabilities.json',
  contractVersions: 'contract_versions.json',
  entryMutationClear: 'entry_mutation_clear_nullable.json',
  entryMutationOmitted: 'entry_mutation_omitted_nullable.json',
  entryView: 'entry_view.json',
  generatedPassword: 'generated_secret_redacted.json',
  generatorParams: 'generator_params.json',
  revealedSecret: 'revealed_secret_redacted.json',
  revisionView: 'revision_view.json',
  unsupportedFutureVersions: 'unsupported_future_versions.json',
  vaultSummary: 'vault_summary.json',
};

function readFixture(name) {
  const path = resolve(fixtureDir, name);
  return JSON.parse(readFileSync(path, 'utf8'));
}

function renderFixture(value) {
  return JSON.stringify(value, null, 2);
}

function render() {
  const entries = Object.entries(fixtures)
    .map(([exportName, fileName]) => {
      const value = renderFixture(readFixture(fileName));
      return `export const ${exportName}Fixture = ${value} as const;\n`;
    })
    .join('\n');

  return `// Generated by apps/desktop/scripts/generate-ipc-contract-fixtures.mjs.\n// Do not edit manually.\n\n${entries}`;
}

const generated = render();

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== generated) {
    console.error(
      'Generated vault-api contract fixtures are stale. Run `pnpm --filter @arca/desktop contract:generate`.',
    );
    process.exit(1);
  }
} else {
  writeFileSync(outputPath, generated);
}
